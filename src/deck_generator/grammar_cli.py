"""``deck-grammar`` — import / check / build grammar-table decks, one per verb.

- **import**: write one config per verb in ``configs/grammar/sources/verbs.yaml``,
  forms from Wiktionary (``cache/kaikki_la/``), then check them. Overwrites the configs.
- **check** (default): validate authored forms against the conjugation rules. No writes.
- **build**: check, then write ``grammar_<config stem>.json`` per config. Refuses on any failure.

Offline: the import reads the kaikki cache, never the network.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

from . import grammar, grammar_kaikki
from .deck_export import DEFAULT_DECKS_DIR, config_hash

GRAMMAR_DIR = Path(__file__).resolve().parents[2] / "configs" / "grammar"
VERBS = GRAMMAR_DIR / "sources" / "verbs.yaml"
NOMINALS = {"noun": GRAMMAR_DIR / "sources" / "nouns.yaml",
            "pronoun": GRAMMAR_DIR / "sources" / "pronouns.yaml"}
CACHE = Path(__file__).resolve().parents[2] / "cache" / "kaikki_la"
_HEADER = ("# One paradigm deck, page by page → one quiz `grammar-table` deck (`deck-grammar`).\n"
           "# GENERATED by `deck-grammar --import` from Wiktionary (kaikki.org); every form is\n"
           "# re-derived by grammar.py / grammar_nominal.py and the build refuses on any disagreement.\n"
           "# Fix a form in sources/*.yaml or the rules, never here: the next import overwrites it.\n")


def _print(report: grammar.Report, config: Path) -> None:
    for w in report.warnings:
        print(f"  WARN {w}")
    for f in report.failures:
        print(f"  FAIL {f}")
    print(f"{config.name}: " + ("OK" if report.ok else f"REFUSED — {len(report.failures)} failure(s)"))


def _build(cfg: dict, config: Path, out_dir: Path) -> None:
    art = grammar.assemble_artifact(cfg, f"manual/grammar/{config.name}")
    art["config_hash"] = config_hash(config)
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"grammar_{config.stem}.json"
    out.write_text(json.dumps(art, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"built {out.name} — {len(art['items'])} cards")


def _write(path: Path, cfg: dict) -> Path:
    body = yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False, width=100,
                          default_flow_style=None)
    path.write_text(_HEADER + body, encoding="utf-8")
    return path


def import_configs(verbs_path: Path | None = VERBS, cache: Path = CACHE,
                   out_dir: Path = GRAMMAR_DIR, nominals: dict | None = None) -> list[Path]:
    """Write every verb, noun and pronoun deck config; return their paths in menu order."""
    written = []
    if verbs_path:
        verbs = yaml.safe_load(verbs_path.read_text(encoding="utf-8"))["verbs"]
        for rank, verb in enumerate(verbs):
            stem = grammar_kaikki.config_stem(verb["lemma_key"])
            written.append(_write(out_dir / f"{stem}.yaml",
                                  grammar_kaikki.verb_config(verb, rank, cache)))
    for kind, path in (NOMINALS if nominals is None else nominals).items():
        decks = yaml.safe_load(path.read_text(encoding="utf-8"))["decks"]
        for rank, deck in enumerate(decks):
            stem = grammar_kaikki.nominal_stem(deck, kind)
            written.append(_write(out_dir / f"{stem}.yaml",
                                  grammar_kaikki.nominal_config(deck, kind, rank, cache)))
    return written


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description="Import/check/build grammar-table decks.")
    p.add_argument("--config", type=Path, nargs="+", help="configs/grammar/<slug>.yaml ...")
    p.add_argument("--import", dest="do_import", action="store_true",
                   help="regenerate every page config from sources/verbs.yaml + the kaikki cache")
    p.add_argument("--out", type=Path, default=DEFAULT_DECKS_DIR)
    p.add_argument("--build", action="store_true", help="write the artifacts (default: check only)")
    args = p.parse_args(argv)

    configs = import_configs() if args.do_import else args.config
    if not configs:
        p.error("give --config or --import")
    loaded = [(c, yaml.safe_load(c.read_text(encoding="utf-8"))) for c in configs]
    reports = [grammar.validate(cfg) for _, cfg in loaded]
    for (c, _), r in zip(loaded, reports):
        _print(r, c)
    if not all(r.ok for r in reports):
        sys.exit(1)
    if args.build:
        for c, cfg in loaded:
            _build(cfg, c, args.out)
        print(f"{len(loaded)} decks (source: manual) — NOT synced: copy to "
              "memory-quiz-app/data/decks/ by hand.")
    sys.exit(0)


if __name__ == "__main__":
    main()
